"""Native color-buffer constructors using the current MXCSR rounding mode.

The delegated blue argument is evaluated before the real buffer member's
initialization. This source ordering and the measured legacy SSA profile emit
the complete 111-byte client constructor; no inline assembly or injected code.
"""
import json
import pathlib
import sys

ROOT=pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'tools'))
import match_func as M

RVA=0x6582d0
NAMES=('LoadingScreenSummonerNameData','LoadingScreenSummonerTitleData')
FLAGS=['-O2','-std:c++17','-d2SSAOptimizer-']
SOURCE=ROOT/'client-src/src/gen/ReflectedColorConstructors.cpp'
EXPECTED_TEXT='''cvtss2si eax, dword ptr [0x153f9e0]
mov dword ptr [ecx], 0
mov dword ptr [ecx + 4], 0
mov dword ptr [ecx + 8], 0
movss xmm2, dword ptr [0x153f9e4]
mov byte ptr [ecx + 0xe], al
cvtss2si eax, dword ptr [0x1b2d5d0]
mov byte ptr [ecx + 0xd], al
cvtss2si eax, dword ptr [0x1535424]
mov byte ptr [ecx + 0xc], al
cvtss2si eax, xmm2
mov byte ptr [ecx + 0xf], al
cvtss2si eax, dword ptr [0x1b2d5dc]
mov byte ptr [ecx + 0x12], al
cvtss2si eax, dword ptr [0x1b2d5d8]
mov byte ptr [ecx + 0x11], al
cvtss2si eax, dword ptr [0x1b2d5d4]
mov byte ptr [ecx + 0x10], al
cvtss2si eax, xmm2
mov byte ptr [ecx + 0x13], al
mov eax, ecx
ret'''
GLOBALS=(0x153f9e0,0x153f9e4,0x1b2d5d0,0x1535424,0x1b2d5dc,0x1b2d5d8,0x1b2d5d4)


def helper_declaration(im,name,row):
    if name not in NAMES:return []
    if row['native_ctor']!=RVA or row['size']!=20 or row['member']['element']!='UiHashLink' or im.text(RVA)!=EXPECTED_TEXT:
        raise ValueError('Color-buffer constructor evidence changed')
    return ['private:',f'    __forceinline {name}(int blue);','public:']


def render(claims=True):
    lines=['// Native color-buffer construction, including the real rounded byte conversions.',
           '// Generated by tools/gen_reflected_colors.py; equivalent profile measured on all 111 bytes.',
           '// flags: '+' '.join(FLAGS)]
    if claims:
        lines += [f'// {"match" if i==0 else "same"}: {RVA:x} ??0{name}@@QAE@XZ' for i,name in enumerate(NAMES)]
    lines += ['#include "BinClasses.h"','#include <xmmintrin.h>',
              'extern float '+', '.join(f'g_{va:x}' for va in GLOBALS)+';']
    for name in NAMES:
        lines += [f'{name}::{name}() : {name}(_mm_cvtss_si32(_mm_load_ss(&g_153f9e0))) {{}}',
                  f'{name}::{name}(int blue) {{',
                  '    const __m128 alpha = _mm_load_ss(&g_153f9e4);',
                  '    unknown0c[2] = (u8)blue;',
                  '    unknown0c[1] = (u8)_mm_cvtss_si32(_mm_load_ss(&g_1b2d5d0));',
                  '    unknown0c[0] = (u8)_mm_cvtss_si32(_mm_load_ss(&g_1535424));',
                  '    unknown0c[3] = (u8)_mm_cvtss_si32(alpha);',
                  '    unknown0c[6] = (u8)_mm_cvtss_si32(_mm_load_ss(&g_1b2d5dc));',
                  '    unknown0c[5] = (u8)_mm_cvtss_si32(_mm_load_ss(&g_1b2d5d8));',
                  '    unknown0c[4] = (u8)_mm_cvtss_si32(_mm_load_ss(&g_1b2d5d4));',
                  '    unknown0c[7] = (u8)_mm_cvtss_si32(alpha);','}']
    return '\n'.join(lines)+'\n'


def verify(path):
    obj=M.compile_obj(str(path),FLAGS)
    results=[]
    expected={f'?g_{va:x}@@3MA':va-0x580000 for va in GLOBALS}
    for name in NAMES:
        symbol=f'??0{name}@@QAE@XZ'
        compared=M.compare(str(path),symbol,RVA,FLAGS,obj)
        _,code,_=M.function_of(obj,symbol)
        targets=dict(M.symbol_addresses(RVA,code))
        if compared[3] is not None or targets!=expected:
            raise ValueError(f'Color constructor differs: {name}: {compared}: {targets}')
        results.append(dict(name=name,rva=hex(RVA),bytes=compared[1],targets=targets))
    return results


def main():
    probe=ROOT/'client-src/obj/root_real_color_constructors.cpp'
    source=render(False).replace('#include "BinClasses.h"',f'#include "{(SOURCE.parent/"BinClasses.h").as_posix()}"')
    probe.write_text(source,encoding='utf-8')
    verify(probe)
    SOURCE.write_text(render(),encoding='utf-8',newline='\n')
    M.rebuilt_symbols.__dict__.pop('v',None)
    audit=verify(SOURCE)
    (ROOT/'client-src/obj/root_real_color_constructors_audit.json').write_text(json.dumps(audit,indent=2),encoding='utf-8')
    print('Color buffer constructors:',len(audit),'one folded RVA, 111 bytes + seven float globals verified')


if __name__=='__main__':main()
