"""Prove simple reflected list layouts through all four native lifecycle callbacks.

The emitted runtime type is distinct from the serialized container tag. Only
single-buffer classes whose complete C++ callbacks match are published. Metadata
and callback shapes are rechecked before their layout is used by gen_meta.py.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'tools'))
import match_func as M

GEN = ROOT/'client-src/src/gen'
HEADER = GEN/'ReflectedBuffers.h'
CALLBACKS = GEN/'ReflectedBufferCallbacks.cpp'
NATIVE = GEN/'ReflectedBufferNative.cpp'
MANIFEST = ROOT/'tools/reflected_buffer_layouts.json'
HEADER_SOURCE = '''// Measured twelve-byte storage; serialized container tags remain in MetaClasses.h.
// Generated by tools/gen_reflected_buffers.py. Only proved reflected owners use this type.
#pragma once
#include "UiResourceRefs.h"
template<class E> struct ReflectedBuffer {
    E* data = nullptr;
    u32 count = 0;
    int capacity = 0; // high bit prevents deallocation; element lifetimes still end
    __forceinline ~ReflectedBuffer() {
        for (auto p = data, end = data + count; p < end; ++p) p->~E();
        if (capacity >= 0) ::operator delete(data);
    }
};
static_assert(sizeof(ReflectedBuffer<float>) == 12, "native reflected buffer ABI");
template<class K, class V> struct ReflectedPair { K key; V value; };
'''
CALLBACK_ORDER = [('create','MetaCreate','PAXXZ'),('construct','MetaConstruct','XPAX@Z'),
                  ('destroy','MetaDestroy','XPAX@Z'),('destruct','MetaDestruct','XPAX@Z')]


def candidate(im,a,f,g):
    import gen_meta as A
    if f['parent'] is not None or f['poly'] or f['align'] != 4 or f['size'] < 12:
        return None
    members=[]
    for event in a.followed.get(g, ()):
        if event[0]!='call' or event[2]!=g or event[1]==A.META_CTOR:
            continue
        args=event[3]
        descriptor=A.container_wrapper(im,event[1])
        if len(args)!=3 or any(value[0]!='imm' for value in args):
            return None
        if args[1][1]>=12:
            # Scalar tails remain represented by their measured stores or opaque bytes.
            primitive=A.member_wrapper(im,event[1])
            if not primitive or primitive[1]!=0 or primitive[0] not in A.PRIM_SIZE:
                return None
            continue
        if args[1][1]!=0 or not descriptor:
            return None
        typ=None;stride=None
        if descriptor['code']==0x86 and descriptor['slot']==6 and descriptor['of'] is None:
            codes=descriptor['stores'].get(4)
            if codes and codes[0]==2:
                key,value=codes[1]&255,codes[1]>>8
                if key in A.PRIM_SIZE and value in A.PRIM_SIZE:
                    typ=f'ReflectedPair<{A.PRIMITIVE[key]}, {A.PRIMITIVE[value]}>'
        elif descriptor['code'] not in (0x80,0x81) or descriptor['slot']!=5:
            return None
        element=descriptor['stores'].get(4)
        if descriptor['slot']==5:
            stride=descriptor['stores'].get(8)
            if not element or not stride or element[0]!=1 or stride[0]!=4:
                return None
            if descriptor['of'] is None:
                typ={(0xa,4):'float',(7,4):'u32',(0x10,12):'MetaString',
                     (0x11,4):'HashValue',(0x11,12):'UiHashKey',(0x11,24):'UiHashLink'}.get((element[1],stride[1]))
            elif element[1]==0x83:
                typ=a.element(element[1],stride[1],descriptor['of'])
        if typ is None:
            return None
        members.append(dict(name=A.cpp_member_name(a.names.get(args[0][1]) or f'm_{args[0][1]:08x}'),
            hash=args[0][1],wrapper=event[1],element=typ,stride=stride[1] if stride else None,descriptor=descriptor))
    if len(members)!=1 or not all(f[key] for key,_,_ in CALLBACK_ORDER):
        return None
    tail=[]
    if f['size']>12:
        stores=A.constant_construct(im,f['construct'],f['size'],sse=True)
        if stores and stores[:3]==[(0,4,0),(4,4,0),(8,4,0)]:
            tail=A.constant_members([(off-12,width,value) for off,width,value in stores[3:]],f['size']-12,4)
            tail=[re.sub(r'unknown([0-9a-f]+)',lambda m:f'unknown{int(m[1],16)+12:02x}',line) for line in tail]
        else:
            tail=[f'    u8 unknown0c[{f["size"]-12:#x}];']
    native_targets={item[2] for item in (A.out_of_line(im,f['create']),A.out_of_line(im,f['construct']))
                    if item and item[0] in ('create','jump')}
    native_ctor=next(iter(native_targets)) if len(native_targets)==1 else None
    cleanup_targets={item[2] for item in (A.out_of_line(im,f['destroy']),A.out_of_line(im,f['destruct']))
                     if item and item[0] in ('delete','jump')}
    native_dtor=next(iter(cleanup_targets)) if len(cleanup_targets)==1 else None
    return dict(name=a.cls[g],size=f['size'],align=f['align'],member=members[0],tail=tail,
                native_ctor=native_ctor,native_dtor=native_dtor,
                native_dtor_body=im.text(native_dtor) if native_dtor is not None else None,
                callbacks={key:f[key] for key,_,_ in CALLBACK_ORDER},
                bodies={key:im.text(f[key]) for key,_,_ in CALLBACK_ORDER})


def layout_of(im,a,f,g):
    rows=json.loads(MANIFEST.read_text(encoding='utf-8')) if MANIFEST.exists() else []
    saved=next((row for row in rows if row['name']==a.cls[g]),None)
    if saved is None:
        return None
    current=json.loads(json.dumps(candidate(im,a,f,g)))
    if current!=saved:
        raise ValueError(f'Reflected buffer evidence changed: {a.cls[g]}')
    member=saved['member']
    import gen_reflected_colors
    return [*gen_reflected_colors.helper_declaration(im,a.cls[g],saved),
            f'    ReflectedBuffer<{member["element"]}> {member["name"]};     // +0x0, count and signed ownership capacity',*saved.get('tail',[])]


def definitions(rows):
    return [f'template <> void* MetaCreate<{row["name"]}>() {{ return new {row["name"]}; }}' if key=='create' else
            f'template <> void MetaConstruct<{row["name"]}>(void* p) {{ new (p) {row["name"]}; }}' if key=='construct' else
            f'template <> void MetaDestroy<{row["name"]}>(void* p) {{ delete static_cast<{row["name"]}*>(p); }}' if key=='destroy' else
            f'template <> void MetaDestruct<{row["name"]}>(void* p) {{ static_cast<{row["name"]}*>(p)->~{row["name"]}(); }}'
            for row in rows for key,_,_ in CALLBACK_ORDER]


NATIVE_TARGETS={'??2@YAPAXI@Z':0x9bb8d0,'??3@YAXPAX@Z':0x9bb930,'??3@YAXPAXI@Z':0x9bb940,
                '??1RString@@QAE@XZ':0x9bab90,'??1UiResourceReference@@UAE@XZ':0xae14d0}


def native_definitions(rows):
    return [f'__declspec(noinline) {row["name"]}::~{row["name"]}() = default;'
            for row in rows if row.get('native_dtor') is not None]


def verify_native(path,rows):
    obj=M.compile_obj(str(path),M.FLAGS)
    verified,rejected=[],[]
    for row in rows:
        if row.get('native_dtor') is None:continue
        symbol=f'??1{row["name"]}@@QAE@XZ'
        result=M.compare(str(path),symbol,row['native_dtor'],M.FLAGS,obj)
        _,code,_=M.function_of(obj,symbol)
        targets=M.symbol_addresses(row['native_dtor'],code)
        details=dict(name=row['name'],rva=row['native_dtor'],result=result,targets=targets)
        (rejected if result[3] is not None or any(NATIVE_TARGETS.get(sym)!=target for sym,target in targets)
         else verified).append(details)
    return verified,rejected


def verify(path,rows,native_verified=()):
    obj=M.compile_obj(str(path),M.FLAGS)
    verified,rejected=[],[]
    # The bodies use only the already proved operators and two native dtors.
    expected=NATIVE_TARGETS
    proved={item['name']:item['rva'] for item in native_verified}
    for row in rows:
        details=[]
        allowed=dict(expected)
        if row['name'] in proved and proved[row['name']]==row.get('native_dtor'):
            allowed[f'??1{row["name"]}@@QAE@XZ']=row['native_dtor']
        if row.get('native_ctor') is not None:
            # The two metadata wrappers independently establish this exact call
            # address and thiscall receiver. This is an interface binding, not a
            # claim that the constructor's own body has been reconstructed.
            allowed[f'??0{row["name"]}@@QAE@XZ']=row['native_ctor']
        for key,fn,suffix in CALLBACK_ORDER:
            symbol=f'??${fn}@U{row["name"]}@@@@YA{suffix}'
            rva=row['callbacks'][key]
            result=M.compare(str(path),symbol,rva,M.FLAGS,obj)
            _,code,_=M.function_of(obj,symbol)
            targets=M.symbol_addresses(rva,code)
            if result[3] is not None or any(allowed.get(sym)!=target for sym,target in targets):
                details.append(dict(key=key,result=result,targets=targets))
        (rejected if details else verified).append(dict(row=row,failures=details) if details else row)
    return verified,rejected


def main():
    import gen_sources as G
    import gen_meta as A
    im=G.Image();a=A.analysis(im);facts=A.class_facts(im,a)
    rows=[row for g,f in facts.items() if a.cls[g] in a.unique
          for row in [candidate(im,a,f,g)] if row is not None]
    rows.sort(key=lambda row:row['name'])
    probe=ROOT/'client-src/obj/root_reflected_buffer_candidates.cpp'
    header=ROOT/'client-src/obj/root_reflected_buffers.h'
    header.write_text(HEADER_SOURCE.replace('#include "UiResourceRefs.h"',
        f'#include "{(GEN/"UiResourceRefs.h").as_posix()}"'),encoding='utf-8')
    base_header=(GEN/'BinClasses.h').read_text(encoding='utf-8')
    for row in rows:
        pattern=r'(struct '+re.escape(row['name'])+r'\n\{\n)(.*?)(\n\};)'
        def replace(match):
            declarations=[line for line in match[2].splitlines() if re.match(r'\s*(?:~)?'+re.escape(row['name'])+r'\(\);',line)]
            member=f'    ReflectedBuffer<{row["member"]["element"]}> {row["member"]["name"]};'
            return match[1]+'\n'.join([*declarations,member,*row['tail']])+match[3]
        base_header,n=re.subn(pattern,replace,base_header,flags=re.S)
        if n!=1:raise ValueError('No unique candidate class definition: '+row['name'])
    base_header=re.sub(r'^#include "([^"]+)"',lambda m:'#include "'+(GEN/m[1]).resolve().as_posix()+'"',base_header,flags=re.M)
    base_header=base_header.replace(f'#include "{HEADER.as_posix()}"','#include "root_reflected_buffers.h"')
    candidate_header=ROOT/'client-src/obj/root_reflected_buffer_candidate_classes.h'
    candidate_header.write_text(base_header,encoding='utf-8')
    probe.write_text('\n'.join(['#include "root_reflected_buffer_candidate_classes.h"',*definitions(rows),'']),encoding='utf-8')
    native_probe=ROOT/'client-src/obj/root_reflected_buffer_native_candidates.cpp'
    native_probe.write_text('\n'.join(['#include "root_reflected_buffer_candidate_classes.h"',*native_definitions(rows),'']),encoding='utf-8')
    native_good,native_bad=verify_native(native_probe,rows)
    kept,rejected=verify(probe,rows,native_good)
    HEADER.write_text(HEADER_SOURCE,encoding='utf-8',newline='\n')
    MANIFEST.write_text(json.dumps(kept,indent=2)+'\n',encoding='utf-8')
    # Generate the dependent classes before compiling the final owned callbacks.
    lines,_=A.bin_classes(im,a)
    (GEN/'BinClasses.h').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    native_kept=[row for row in kept if any(item['name']==row['name'] for item in native_good)]
    native_claims=[f'// match: {row["native_dtor"]:x} ??1{row["name"]}@@QAE@XZ' for row in native_kept]
    NATIVE.write_text('\n'.join(['// Native defaulted reflected buffer destructors; compiled separately from callbacks.',
        '// Generated by tools/gen_reflected_buffers.py.',*native_claims,'#include "BinClasses.h"',*native_definitions(native_kept),'']),encoding='utf-8',newline='\n')
    native_final,native_failed=verify_native(NATIVE,native_kept)
    if native_failed:raise ValueError('Published native buffer destructors changed: '+str(native_failed))
    claimed=set()
    for source in M.sources():
        if pathlib.Path(source).resolve()==CALLBACKS.resolve():continue
        claimed.update(int(rva,16) for rva in re.findall(r'^// match: ([0-9a-f]+)',pathlib.Path(source).read_text(encoding='utf-8'),re.M))
    claims=[]
    for row in kept:
        for key,fn,suffix in CALLBACK_ORDER:
            rva=row['callbacks'][key]
            kind='same' if rva in claimed else 'match'
            claimed.add(rva)
            claims.append(f'// {kind}: {rva:x} ??${fn}@U{row["name"]}@@@@YA{suffix}')
    CALLBACKS.write_text('\n'.join(['// Native reflected buffer lifetimes; every owner has four verified C++ bodies.',
        '// Generated by tools/gen_reflected_buffers.py.',*claims,'#include "BinClasses.h"',*definitions(kept),'']),encoding='utf-8',newline='\n')
    M.rebuilt_symbols.__dict__.pop('v',None)
    final,bad=verify(CALLBACKS,kept,native_final)
    if bad:raise ValueError('Published reflected buffer callbacks changed: '+str(bad))
    (ROOT/'client-src/obj/root_reflected_buffer_audit.json').write_text(json.dumps(dict(verified=final,rejected=rejected,
        native_verified=native_final,native_rejected=native_bad),indent=2),encoding='utf-8')
    print('Verified reflected buffers:',len(final),'callbacks:',4*len(final),'native dtors:',len(native_final),'rejected:',len(rejected),flush=True)


if __name__=='__main__':main()
