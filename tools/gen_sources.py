def main():
    names = sys.argv[1:] or list(PATTERNS)
    im = Image()
    os.makedirs(OUT, exist_ok=True)
    for name in names:
        path = os.path.join(OUT, name)
        im.exclude(path)
        failed = set()
        for attempt in range(4):
            im.done |= failed
            if hasattr(im, 'meta'):
                for k in ('facts', 'defined', 'laid_out', 'children'):
                    im.meta.__dict__.pop(k, None)
            lines, n = PATTERNS[name](im)
            with open(path, 'w', newline=NL, encoding='utf-8') as f:
                f.write(NL.join(lines) + NL)
            if name in PRUNE:
                gone = prune(path)
                n -= gone
                print(f'{name}: {gone} candidate functions removed (not identical)')
            if not path.endswith('.cpp'):
                break
            # every claim checked: the ones that are not identical are left out and the file written again
            bad = verify(path)
            if not bad:
                break
            print(f'{name}: {len(bad)} functions not identical, written again without them')
            failed |= bad
        print(f'{name}: {n} functions -> {path}')


def verify(path):
    """rvas of the `// match:` lines of a file whose function is not identical to the client's."""
    src = open(path, encoding='utf-8').read()
    objs = {}
    M.rebuilt_symbols.__dict__.pop('v', None)
    bad = set()
    for m in re.finditer(r'^// match: ([0-9a-f]+) (\S+)(.*)$', src, re.M):
        flags = m[3].split() or M.file_flags(path)
        if tuple(flags) not in objs:
            objs[tuple(flags)] = M.compile_obj(path, flags)
        if M.compare(path, m[2], int(m[1], 16), flags, objs[tuple(flags)])[3] is not None:
            bad.add(int(m[1], 16))
    return bad


if __name__ == '__main__':
    main()
