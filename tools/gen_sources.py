"""Sources for the client's mass-produced functions, written from the client itself: shapes the compiler repeats for
every global, every lambda, every class of a kind (tools/shapes.py finds them). Each pattern is a list of instruction
lines (regular expressions over capstone's text, branch targets as rvas, immediates as virtual addresses); a
function that matches gets its line of source, and the generated file names every function it stands for with
"// match:" lines, so tools/match_all.py proves each one against the client.

Names of the generated globals and types are ours: g_<virtual address> for a global, the address being the client's.

  gen_sources.py [file ...]     -> client-src/src/gen/<file> (all of them by default)
"""
