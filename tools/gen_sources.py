NL = chr(10)


def c_string(va):
    """The NUL-terminated string at a virtual address, written as a C literal."""
    o = va - P.BASE
    raw = bytes(P.IMG[o:P.IMG.index(0, o)])
    out = []
    for b in raw:
        if b in (0x22, 0x5c):
            out.append(chr(92) + chr(b))
        elif 0x20 <= b < 0x7f and b != 0x3f:          # '?' left out: trigraph-free
            out.append(chr(b))
        else:
            out.append(chr(92) + format(b, '03o'))
    return '"' + ''.join(out) + '"'


class Image:
    def __init__(self):
        from capstone import Cs, CS_ARCH_X86, CS_MODE_32
        self.md = Cs(CS_ARCH_X86, CS_MODE_32)
        self.img = bytes(P.IMG)
        self.starts = sorted(M.starts())
        self.done = set(M.rebuilt_symbols())

    def exclude(self, path):
        """Functions rebuilt anywhere but in path (the file being written again)."""
        self.done = set()
        for src in M.sources():
            if os.path.abspath(src) != os.path.abspath(path):
                for m in re.finditer(r'^// match: ([0-9a-f]+) ', open(src, encoding='utf-8').read(), re.M):
                    self.done.add(int(m.group(1), 16))

    def size(self, rva):
        k = bisect.bisect_right(self.starts, rva)
        e = self.starts[k] if k < len(self.starts) else TEXT1
        while e > rva and self.img[e - 1] == 0xcc:
            e -= 1
        return e - rva

    def text(self, rva):
        n = self.size(rva)
        lines, end = [], 0
        for i in self.md.disasm(self.img[rva:rva + n], rva):
            lines.append(f'{i.mnemonic} {i.op_str}'.strip())
            end = i.address + i.size - rva
        return NL.join(lines) if end == n else None


def pattern(*lines):
    return re.compile(NL.join(lines) + r'\Z')


H = r'(0x[0-9a-f]+)'


def rstring_globals(im):
    """Globals of type RString made from a literal: the dynamic initializer and its atexit callback."""
    init = pattern(r'push (?P<lit>0x[0-9a-f]+)', 'call 0x9daf30', 'add esp, 4',
                   r'mov dword ptr \[(?P<g>0x[0-9a-f]+)\], (?P=lit)', r'mov dword ptr \[(?P<g4>0x[0-9a-f]+)\], eax',
                   'test al, 1', 'je ' + H, 'inc eax', r'push (?P<f>0x[0-9a-f]+)',
                   r'mov dword ptr \[(?P<g8>0x[0-9a-f]+)\], eax', 'call 0xf411a5', 'pop ecx', 'ret')
    rows = []
    for s in im.starts:
        if s in im.done or im.img[s] != 0x68:
            continue
        t = im.text(s)
        m = t and init.match(t)
        if not m:
            continue
        g = int(m['g'], 16)
        if int(m['g4'], 16) != g + 4 or int(m['g8'], 16) != g + 8:
            continue
        f = int(m['f'], 16) - P.BASE
        ft = im.text(f) if f in im.starts else None
        rows.append((s, g, int(m['lit'], 16), f if ft == f'mov ecx, {g:#x}{NL}jmp 0x9bab90' else None))
    out = ['// Globals of type RString made from a string literal (generated by tools/gen_sources.py from the client).',
           '// Each line is one global; the compiler writes its dynamic initializer (??__E) and the atexit callback',
           '// that destroys it (??__F). Global names are ours: g_<the global\'s virtual address in the client>.']
    for s, g, lit, f in rows:
        out.append(f'// match: {s:x} ??__Eg_{g:x}@@YAXXZ')
        if f is not None:
            out.append(f'// match: {f:x} ??__Fg_{g:x}@@YAXXZ')
    out += ['#include "../RString.h"', '']
    out += [f'RString g_{g:x}({c_string(lit)});' for s, g, lit, f in rows]
    return out, len(rows) + sum(1 for r in rows if r[3] is not None)


def hash_names(kinds=('bintypes', 'binfields')):
    """FNV-1a hash -> Riot's name, for .bin classes and / or members (data/hashes, CommunityDragon's lists)."""
    out = {}
    for f in (f'hashes.{k}.txt' for k in kinds):
        for line in open(os.path.join(ROOT, 'data', 'hashes', f), encoding='utf-8', errors='replace'):
            p = line.split()
            if len(p) == 2 and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', p[1]):
                out[int(p[0], 16)] = p[1]
    return out


def global_instances(im):
    """Deleting destructors of GlobalInstance<T> (ZoneB_GlobalInstance.h): the base of one-of-a-kind objects that
    keeps the object's address in a global pointer of its own. T is unknown; it is named after the destructor."""
    dtor = pattern(r'test byte ptr \[esp \+ 4\], 1', 'push esi', 'mov esi, ecx', r'mov dword ptr \[esi\], 0x[0-9a-f]+',
                   r'mov dword ptr \[0x[0-9a-f]+\], 0', 'je ' + H, 'push 4', 'push esi', 'call 0x9bb940',
                   'add esp, 8', 'mov eax, esi', 'pop esi', 'ret 4')
    found = [s for s in im.starts if s not in im.done and im.img[s] == 0xf6 and dtor.match(im.text(s) or '')]
    out = ['// The deleting destructors of GlobalInstance<T> (ZoneB_GlobalInstance.h; generated by tools/gen_sources.py),',
           '// one per class that has that base. What the classes are is not known; each is named after the rva of',
           '// this destructor. The base\'s table (one entry) and the global pointer it clears are relocations.']
    out += [f'// match: {s:x} ??_G?$GlobalInstance@UObject{s:x}@@@@UAEPAXI@Z' for s in found]
    out += ['#include "../ZoneB_GlobalInstance.h"', '']
    out += [f'struct Object{s:x};' for s in found] + ['']
    out += [f'template struct GlobalInstance<Object{s:x}>;' for s in found]
    return out, len(found)


def literal_at(im, addrs):
    """The string literal that a set of addresses (loads of its pieces) points into: (start, text) or None."""
    rd = sorted(a for a in addrs if 0xfab000 <= a - P.BASE < 0x1752000)
    if not rd:
        return None
    start = rd[0] - P.BASE
    end = im.img.index(0, start)
    if rd[-1] - P.BASE > end or (start and im.img[start - 1] not in (0,)):
        return None
    return rd[0], bytes(im.img[start:end])


def short_literal(lines):
    """A literal of at most 15 characters that the code writes straight into a std::string on the stack (immediate
    stores into the small-string buffer at esp + 0, its size at +0x10): the C literal, or None."""
    delta, buf, size = 0, {}, None
    for x in lines:
        if x.startswith('push '):
            delta += 4
            continue
        m = re.fullmatch(r'add esp, (0x[0-9a-f]+|\d+)', x)
        if m:
            delta -= int(m[1], 0)
            continue
        if x.startswith('call '):
            break
        m = re.fullmatch(r'mov (byte|word|dword) ptr \[esp(?: \+ (0x[0-9a-f]+|\d+))?\], (0x[0-9a-f]+|\d+)', x)
        if m:
            k = int(m[2] or '0', 0) - delta
            n = {'byte': 1, 'word': 2, 'dword': 4}[m[1]]
            v = int(m[3], 0)
            if k == 0x10 and n == 4:
                size = v
            elif 0 <= k < 0x10:
                for j in range(n):
                    buf[k + j] = (v >> (8 * j)) & 0xff
    if size is None or size > 15 or any(j not in buf for j in range(size)):
        return None
    raw = bytes(buf[j] for j in range(size))
    if 0 in raw:
        return None
    out = []
    for b in raw:
        if b in (0x22, 0x5c):
            out.append(chr(92) + chr(b))
        elif 0x20 <= b < 0x7f and b != 0x3f:
            out.append(chr(b))
        else:
            out.append(chr(92) + format(b, '03o'))
    return '"' + ''.join(out) + '"'


def elf_keys(im):
    """Globals of type ElfKey (ElfKey.h): start-up functions that hash a literal through a std::string with
    HashElf (rva 0x120eb0), store the result in a global and register its atexit callback. Candidates; the ones that
    do not compile to the client's bytes are removed by prune()."""
    out_matches, defs = [], []
    for s in im.starts:
        if s in im.done or not 0x1000 <= s < 0xb0000:
            continue
        t = im.text(s)
        if not t or 'call 0x120eb0' not in t or f'call {0xf411a5:#x}' not in t:
            continue
        lines = t.split(NL)
        if sum(1 for x in lines if x == 'call 0x120eb0') != 1:
            continue
        k = lines.index('call 0x120eb0')
        g = None
        for x in lines[k + 1:]:
            m = re.fullmatch(r'mov dword ptr \[(0x[0-9a-f]+)\], eax', x)
            if m:
                g = int(m[1], 16)
                break
        f = None
        for a, b in zip(lines, lines[1:]):
            if b == 'call 0xf411a5' and a.startswith('push 0x'):
                f = int(a[5:], 16) - P.BASE
        addrs = {int(x, 16) for x in re.findall(r'0x[0-9a-f]+', t)}
        lit = literal_at(im, addrs)
        text = c_string(lit[0]) if lit else short_literal(lines)
        if g is None or f is None or text is None:
            continue
        ft = im.text(f) if f in im.starts else None
        defs.append(f'ElfKey g_{g:x}({text});    // @{s:x}')
        out_matches.append(f'// match: {s:x} ??__Eg_{g:x}@@YAXXZ')
        if ft == 'ret 0':
            out_matches.append(f'// match: {f:x} ??__Fg_{g:x}@@YAXXZ')
    out = ['// Globals of type ElfKey (ElfKey.h; generated by tools/gen_sources.py from the client): each is the ELF hash',
           '// of a name, made at start-up. Global names are ours: g_<the global\'s virtual address in the client>.']
    out += out_matches + ['#include "../ElfKey.h"', ''] + defs
    return out, len(out_matches)


HASHES = {0x98a860: ('Fnv1aLower', 2), 0x98a8b0: ('Fnv1Lower', 1), 0x971a50: ('ElfHashLower', 1),
          0x120eb0: ('HashElf', 1)}


def hash_globals(im):
    """Globals (or arrays of them) of u32 that a start-up function sets to the hash of a literal (Hashes.h): the
    function only pushes the literal (and the start of the hash), calls the hash and stores the result."""
    defs, matches = [], []
    for s in im.starts:
        if s in im.done or not 0x1000 <= s < 0xb0000:
            continue
        t = im.text(s)
        if not t or not any(f'call {h:#x}' in t for h in HASHES):
            continue
        stack, results, stores, ok, eax = [], [], [], True, None
        for line in t.split(NL):
            m = re.fullmatch(r'push (0x[0-9a-f]+|\d+)', line)
            if m:
                stack.append(int(m[1], 0))
                continue
            m = re.fullmatch(r'call (0x[0-9a-f]+)', line)
            if m and int(m[1], 16) in HASHES:
                name, n = HASHES[int(m[1], 16)]
                if len(stack) < n:
                    ok = False
                    break
                eax = (name, stack[len(stack) - n:][::-1])
                continue
            m = re.fullmatch(r'add esp, (0x[0-9a-f]+|\d+)', line)
            if m:
                k = int(m[1], 0) // 4
                if k > len(stack):
                    ok = False
                    break
                del stack[len(stack) - k:]
                continue
            m = re.fullmatch(r'mov dword ptr \[(0x[0-9a-f]+)\], eax', line)
            if m and eax:
                stores.append((int(m[1], 16), eax))
                continue
            if line == 'ret' and not stack:
                break
            ok = False
            break
        if not ok or not stores:
            continue
        exprs = []
        for g, (name, args) in stores:
            lit = literal_at(im, {args[0]})
            if not lit or lit[0] != args[0]:
                ok = False
                break
            extra = ''
            if name == 'Fnv1aLower':
                extra = '' if args[1] == 0x811c9dc5 else f', {args[1]:#x}'
            exprs.append((g, f'{name}({c_string(args[0])}{extra})'))
        gs = [g for g, _ in exprs]
        if not ok or gs != list(range(gs[0], gs[0] + 4 * len(gs), 4)):
            continue
        g0 = gs[0]
        if len(exprs) == 1:
            defs.append(f'u32 g_{g0:x} = {exprs[0][1]};    // @{s:x}')
        else:
            defs.append(f'u32 g_{g0:x}[{len(exprs)}] = {{    // @{s:x}')
            defs += [f'    {e},' for _, e in exprs] + [f'}};    // g_{g0:x} end']
        matches.append(f'// match: {s:x} ??__Eg_{g0:x}@@YAXXZ')
    out = ['// Globals set at start-up to the hash of a name (Hashes.h, ElfKey.h; generated by tools/gen_sources.py from',
           '// the client). Global names are ours: g_<the global\'s virtual address in the client>.']
    out += matches + ['#include "../Hashes.h"', '#include "../ElfKey.h"', ''] + defs
    return out, len(matches)


def map_globals(im):
    """Globals of type std::map<K, V> made from an initializer list (MSVC's map: head node of 0x18+ bytes from
    operator new, _Find_lower_bound and _Insert_node per element). The pairs are read from the stores that build
    the list on the stack; a value that points at a string literal is a const char*, any other an int. Candidates;
    prune() keeps the ones that compile to the client's bytes."""
    defs, matches = [], []
    for s in im.starts:
        if s in im.done or not 0x1000 <= s < 0xb0000:
            continue
        t = im.text(s)
        if not t or 'call 0x124b60' not in t or 'call 0x9bb8d0' not in t:
            continue
        lines = t.split(NL)
        k = lines.index('call 0x9bb8d0')
        g = None
        for x in lines[k:]:
            m = re.fullmatch(r'mov dword ptr \[(0x[0-9a-f]+)\], e[a-d]x', x)
            if m:
                g = int(m[1], 16)
                break
        delta, stores = 0, {}
        for x in lines[:k]:
            if x.startswith('push '):
                delta += 4
                continue
            m = re.fullmatch(r'mov (byte|dword) ptr \[esp \+ (0x[0-9a-f]+|\d+)\], (0x[0-9a-f]+|\d+)', x)
            if m:
                stores[int(m[2], 0) - delta] = (m[1], int(m[3], 0))
        offs = sorted(stores)
        if g is None or len(offs) < 2 or len(offs) % 2 or offs != list(range(offs[0], offs[0] + 4 * len(offs), 4)):
            continue
        widths = {stores[o][0] for o in offs[1::2]}
        if any(stores[o][0] != 'dword' for o in offs[::2]) or len(widths) != 1:
            continue
        byte_values = widths == {'byte'}
        stores = {o: v for o, (w, v) in stores.items()}
        f = None
        for a, b in zip(lines, lines[1:]):
            if b == 'call 0xf411a5' and a.startswith('push 0x'):
                f = int(a[5:], 16) - P.BASE
        vals = [stores[o] for o in offs]

        def cpp(v):
            lit = literal_at(im, {v}) if 0xfab000 <= v - P.BASE < 0x1752000 else None
            return (c_string(v), 'const char*') if lit and lit[0] == v else (f'{v:#x}' if v > 9 else str(v), 'int')
        pairs = [(cpp(vals[i]), cpp(vals[i + 1])) for i in range(0, len(vals), 2)]
        if byte_values:                 # one-byte values: an enum of its own too
            pairs = [(a, (f'Value_{g:x}({b[0]})', 'byte')) for a, b in pairs]
        kt, vt = {p[0][1] for p in pairs}, {p[1][1] for p in pairs}
        if len(kt) != 1 or len(vt) != 1:
            continue
        # each map has a key type of its own in the client (its constructor is inline: one user per instantiation);
        # an int key is an enum whose name is not known
        kt, vt = kt.pop(), vt.pop()
        if vt == 'byte':
            defs.append(f'enum class Value_{g:x} : unsigned char;    // @{s:x}')
            vt = f'Value_{g:x}'
        if kt == 'int':
            defs.append(f'enum class Enum_{g:x} : int;    // @{s:x}')
            kt = f'Enum_{g:x}'
            pairs = [((f'{kt}({a[0]})', a[1]), b) for a, b in pairs]
        typ = f'std::map<{kt}, {vt}>'
        body = ', '.join(f'{{{a[0]}, {b[0]}}}' for a, b in pairs)
        defs.append(f'{typ} g_{g:x} = {{{body}}};    // @{s:x}')
        matches.append(f'// match: {s:x} ??__Eg_{g:x}@@YAXXZ')
        if f is not None and im.text(f) and im.text(f).startswith(f'mov ecx, {g:#x}'):
            matches.append(f'// match: {f:x} ??__Fg_{g:x}@@YAXXZ')
    out = ['// Globals of type std::map made from an initializer list, mostly names of enum values (generated by',
           '// tools/gen_sources.py from the client). Global names are ours: g_<the global\'s virtual address>.']
    out += matches + ['#include <map>', ''] + defs
    return out, len(matches)


def hash_tables(im):
    """Globals of type std::unordered_map<u32, int> made from an initializer list of {hash of a name, number}: the
    start-up function hashes each name (Hashes.h), builds the list on the stack and calls the map's constructor
    (out of line), then registers the destructor. Candidates; prune() keeps the identical ones."""
    defs, matches = [], []
    for s in im.starts:
        if s in im.done or not 0x1000 <= s < 0xb0000:
            continue
        t = im.text(s)
        if not t or not any(f'call {h:#x}' in t for h in HASHES) or 'call 0xf411a5' not in t:
            continue
        delta, stack, eax, slots, ok = 0, [], None, {}, True
        begin = end = g = None
        lines = t.split(NL)
        for x in lines:
            m = re.fullmatch(r'push (0x[0-9a-f]+|\d+)', x)
            if m:
                stack.append(int(m[1], 0))
                delta += 4
                continue
            m = re.fullmatch(r'call (0x[0-9a-f]+)', x)
            if m and int(m[1], 16) in HASHES:
                name, n = HASHES[int(m[1], 16)]
                args = stack[len(stack) - n:][::-1]
                lit = literal_at(im, {args[0]}) if len(args) == n else None
                if not lit or lit[0] != args[0]:
                    ok = False
                    break
                extra = '' if name != 'Fnv1aLower' or args[1] == 0x811c9dc5 else f', {args[1]:#x}'
                eax = f'{name}({c_string(args[0])}{extra})'
                continue
            m = re.fullmatch(r'add esp, (0x[0-9a-f]+|\d+)', x)
            if m:
                k = int(m[1], 0)
                del stack[len(stack) - k // 4:]
                delta -= k
                continue
            m = re.fullmatch(r'mov dword ptr \[esp \+ (0x[0-9a-f]+|\d+)\], (0x[0-9a-f]+|\d+|eax)', x)
            if m:
                slots[int(m[1], 0) - delta] = eax if m[2] == 'eax' else int(m[2], 0)
                continue
            m = re.fullmatch(r'lea (eax|ecx), \[esp(?: \+ (0x[0-9a-f]+|\d+))?\]', x)
            if m and begin is None or (m and end is None):
                v = int(m[2] or '0', 0) - delta
                if m[1] == 'eax':
                    end = v
                else:
                    begin = v
                continue
            m = re.fullmatch(r'mov ecx, (0x[0-9a-f]+)', x)
            if m:
                g = int(m[1], 16)
                break
        if not ok or None in (begin, end, g) or (end - begin) % 8 or end <= begin:
            continue
        pairs = []
        for o in range(begin, end, 8):
            k, v = slots.get(o), slots.get(o + 4)
            if not isinstance(k, str) or not isinstance(v, int):
                ok = False
                break
            pairs.append(f'{{{k}, {v}}}')
        if not ok:
            continue
        f = None
        for a, b in zip(lines, lines[1:]):
            if b == 'call 0xf411a5' and a.startswith('push 0x'):
                f = int(a[5:], 16) - P.BASE
        defs.append(f'std::unordered_map<u32, int> g_{g:x} = {{{", ".join(pairs)}}};    // @{s:x}')
        matches.append(f'// match: {s:x} ??__Eg_{g:x}@@YAXXZ')
        if f is not None and (im.text(f) or '').startswith(f'mov ecx, {g:#x}'):
            matches.append(f'// match: {f:x} ??__Fg_{g:x}@@YAXXZ')
    out = ['// Globals of type std::unordered_map<u32, int> from {hash of a name, number} lists (generated by',
           '// tools/gen_sources.py from the client). Global names are ours: g_<the global\'s virtual address>.']
    out += matches + ['#include <unordered_map>', '#include "../Hashes.h"', '#include "../ElfKey.h"', ''] + defs
    return out, len(matches)


def empty_strings(im):
    """Globals `std::string g;`: the empty string is made at compile time, so the start-up function only registers
    the destructor (inline: it reads the capacity at +0x14). Candidates; prune() keeps the identical ones."""
    defs, matches = [], []
    for s in im.starts:
        if s in im.done or not 0x1000 <= s < 0xb0000:
            continue
        m = re.fullmatch(r'push (0x[0-9a-f]+)\ncall 0xf411a5\npop ecx\nret', im.text(s) or '')
        if not m:
            continue
        f = int(m[1], 16) - P.BASE
        fm = re.match(r'mov ecx, dword ptr \[(0x[0-9a-f]+)\]\ncmp ecx, 0x10', im.text(f) or '')
        if not fm:
            continue
        g = int(fm[1], 16) - 0x14
        defs.append(f'std::string g_{g:x};    // @{s:x}')
        matches += [f'// match: {s:x} ??__Eg_{g:x}@@YAXXZ', f'// match: {f:x} ??__Fg_{g:x}@@YAXXZ']
    out = ['// Empty std::string globals (generated by tools/gen_sources.py from the client). Global names are ours:',
           '// g_<the global\'s virtual address in the client>.']
    out += matches + ['#include <string>', ''] + defs
    return out, len(matches)


def library_files(label, src_dir, note, flags='', ext='.cpp', prelude=(), compiler=None, file_flags=None):
    """One source file per library object: it includes the library's own source file and names the client
    functions that object gives (client-src/lib_<label>.tsv from tools/match_objs.py, matches found at one place
    only). The library's code is not rewritten: its public source is the source."""
    def run(im):
        mine = os.path.abspath(os.path.join(OUT, label))
        im.done = set()
        for src in M.sources():
            if not os.path.abspath(src).startswith(mine + os.sep):
                for m in re.finditer(r'^// match: ([0-9a-f]+) ', open(src, encoding='utf-8').read(), re.M):
                    im.done.add(int(m.group(1), 16))
        rows = {}
        for line in open(os.path.join(ROOT, 'client-src', f'lib_{label}.tsv')):
            p = line.rstrip(NL).split(chr(9))
            if line[0] == '#' or p[4] != '1' or int(p[0], 16) in im.done:
                continue
            rows.setdefault(p[2], []).append((int(p[0], 16), p[3]))
        n = 0
        for obj, fns in sorted(rows.items()):
            c = obj[:-4] + '.c'
            path = os.path.join(OUT, label, obj[:-4] + ext)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            srcmap = os.path.join(ROOT, 'client-src', f'lib_{label}.src')
            if os.path.exists(srcmap):
                known = dict(x.rstrip(NL).split(chr(9)) for x in open(srcmap) if x.strip())
                found = [os.path.join(ROOT, known[obj])] if obj in known else []
            else:
                found = glob.glob(os.path.join(ROOT, src_dir, '**', c), recursive=True)
            if len(found) != 1:
                continue
            rel = os.path.relpath(found[0], os.path.dirname(path)).replace(chr(92), '/')
            lines = [f'// {note}: {c}, the functions of it that are in the client (tools/match_objs.py).']
            if compiler:
                lines.append(f'// compiler: {compiler}')
            if file_flags:
                lines.append(f'// flags: {file_flags}')
            lines += [f'// match: {r:x} {sym}' + (f' {flags}' if flags else '') for r, sym in sorted(fns)]
            lines += list(prelude) + [f'#include "{rel}"']
            open(path, 'w', newline=NL, encoding='utf-8').write(NL.join(lines) + NL)
            bad = verify(path)
            if bad:
                lines = [x for x in lines if not (x.startswith('// match: ') and int(x.split()[2], 16) in bad)]
                open(path, 'w', newline=NL, encoding='utf-8').write(NL.join(lines) + NL)
            n += len(fns) - len(bad)
        return [f'// {note}: see the files in {label}/.'], n
    return run


def prune(path):
    """Compile a generated file and remove every item one of whose functions is not identical: its match lines and
    the source lines tagged `// @<rva>` (the rva of the item's first function)."""
    import match_all  # noqa: F401  (same compiler set-up)
    src = open(path, encoding='utf-8').read()
    obj = M.compile_obj(path, M.FLAGS)
    bad = set()
    items = {}
    for m in re.finditer(r'^// match: ([0-9a-f]+) (\S+)$', src, re.M):
        _, _, _, first, _ = M.compare(path, m[2], int(m[1], 16), M.FLAGS, obj)
        if first is not None:
            bad.add(m[2])
    if not bad:
        return 0
    # an item = a tagged source line plus the match lines whose symbol names its global
    keep, gone = [], 0
    lines = src.split(NL)
    tagged = [x for x in lines if re.search(r'// @[0-9a-f]+$', x)]
    dead_names = set()
    for x in tagged:
        name = re.search(r'(g_[0-9a-f]+)(?![0-9a-f])', x)
        if name and any(name[1] + '@' in b for b in bad):
            dead_names.add(name[1])
    skipping = None
    for x in lines:
        if skipping:                    # the rest of a dead multi-line definition
            if f'{skipping} end' in x:
                skipping = None
            continue
        name = re.search(r'(g_[0-9a-f]+)(?![0-9a-f])', x)
        if name and name[1] in dead_names:
            gone += x.startswith('// match:')
            if '{' in x and not x.startswith('//') and '}' not in x:
                skipping = name[1]
            continue
        keep.append(x)
    open(path, 'w', newline=NL, encoding='utf-8').write(NL.join(keep))
    return gone


