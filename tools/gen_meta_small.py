"""Restore reflection callback symbols only through real C++ object operations.

Existing verified Small bodies provide the target address, not a license to
write a synthetic vptr into an opaque C++ object. Construct/create/destruct
specializations use the current real T definitions and survive only after the
full byte and relocation comparison. Empty virtual callbacks are accepted only
if the client body is exactly a return. Existing template instances are excluded.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import match_func as M

GEN = ROOT / 'client-src/src/gen'
OUT = GEN / 'MetaSmallTemplates.cpp'
POSTLOAD_OUT = GEN / 'ViewControllerPostLoad.cpp'
PROBE = ROOT / 'client-src/obj/agent_meta_small_candidates.cpp'
POSTLOAD_PROBE = ROOT / 'client-src/obj/agent_meta_small_postload.cpp'
AUDIT = ROOT / 'client-src/obj/agent_meta_small_audit.json'
SIGNATURE = {'MetaConstruct': 'XPAX@Z', 'MetaCreate': 'PAXXZ',
             'MetaDestruct': 'XPAX@Z', 'MetaDestroy': 'XPAX@Z', 'MetaVirtual2': 'XPAX@Z'}
POSTLOAD_RVA = 0xaefdb0
POSTLOAD_SYMBOL = '?PostLoad@ViewController@@'
POSTLOAD_BODY = '''// PathHashToSelf is the FileLink represented by the eight opaque bytes at +0x30.
// The service receives those bytes; this method does not construct a synthetic subobject.
struct ViewLoadRegistry_ab1550 { void Load(const u8* fileLinkBytes); };
extern int g_36f6118;
void RegisterView_af37c0(ViewController*);
void ViewController::PostLoad() {
    ViewLoadRegistry_ab1550* registry = (ViewLoadRegistry_ab1550*)g_36f6118;
    if (registry) registry->Load(unknown04 + 0x2c);
    if (unknown04[0]) RegisterView_af37c0(this);
}
'''


def dependencies(report):
    candidates = set()
    pattern = r'ours names (\?\?\$(\w+)@U(\w+)@@@@\S+), the client has the rebuilt \?k([0-9a-f]+)@@ there'
    for failure in report['failures']:
        if not failure['source'].endswith('MetaClasses.cpp') or not failure['detail'].startswith('same bytes'):
            continue
        for match in re.finditer(pattern, failure['detail']):
            symbol, fn, name, rva = match.groups()
            if fn in SIGNATURE:
                symbol = f'??${fn}@U{name}@@@@YA{SIGNATURE[fn]}'
                candidates.add((fn, name, int(rva, 16), symbol))
    return sorted(candidates)


def existing_instances():
    instances = set()
    for source in GEN.glob('*.cpp'):
        if source == OUT:
            continue
        text = source.read_text(encoding='utf-8')
        for m in re.finditer(r'^template (?:<>\s*)?(?:void\*|void) (Meta\w+)<(\w+)>\(', text, re.M):
            instances.add((m[1], m[2]))
    return instances


def published_callbacks():
    """Keep proved callbacks when a newer failure report no longer mentions them."""
    if not OUT.exists():
        return []
    result = []
    for m in re.finditer(r'^// (?:same|match): ([0-9a-f]+) (\?\?\$(\w+)@U(\w+)@@@@\S+)',
                         OUT.read_text(encoding='utf-8'), re.M):
        rva, symbol, fn, name = m.groups()
        if fn in SIGNATURE:
            result.append((fn, name, int(rva, 16), symbol))
    return result


def source_body(fn, name, rva=None):
    if fn == 'MetaConstruct':
        return f'template <> void MetaConstruct<{name}>(void* p) {{ new (p) {name}; }}'
    if fn == 'MetaCreate':
        return f'template <> void* MetaCreate<{name}>() {{ return new {name}; }}'
    if fn == 'MetaDestruct':
        return f'template <> void MetaDestruct<{name}>(void* p) {{ static_cast<{name}*>(p)->~{name}(); }}'
    if fn == 'MetaDestroy':
        return f'template <> void MetaDestroy<{name}>(void* p) {{ delete static_cast<{name}*>(p); }}'
    if fn == 'MetaVirtual2':
        if rva == 0x576350:
            return f'template <> void MetaVirtual2<{name}>(void* p) {{ static_cast<{name}*>(p)->ViewController::PostLoad(); }}'
        return f'template <> void MetaVirtual2<{name}>(void*) {{ }}'
    raise ValueError(fn)


def render(items, claims=False, absolute=False):
    header = str(GEN / 'BinClasses.h').replace('\\', '/') if absolute else 'BinClasses.h'
    lines = ['// Reflection callbacks reconstructed with real C++ object operations.',
             '// Generated by tools/gen_meta_small.py; every alias has its own verified body.']
    if claims:
        claimed = set()
        for fn, name, rva, symbol in items:
            # The typed callback owns this body after its synthetic Small
            # counterpart is retired. The other class callbacks are folds.
            kind = 'match' if rva == 0x576350 and rva not in claimed else 'same'
            lines.append(f'// {kind}: {rva:x} {symbol}')
            claimed.add(rva)
    lines += [f'#include "{header}"', '#include <new>', '']
    lines += [source_body(fn, name, rva) for fn, name, rva, symbol in items]
    return '\n'.join(lines) + '\n'


def render_postload(claims=False, absolute=False):
    header = str(GEN / 'BinClasses.h').replace('\\', '/') if absolute else 'BinClasses.h'
    lines = ['// View-controller post-load work, compiled separately from reflection callbacks.',
             '// Generated by tools/gen_meta_small.py; bytes and external targets are verified.']
    if claims:
        lines += [f'// match: {POSTLOAD_RVA:x} {POSTLOAD_SYMBOL}']
    lines += [f'#include "{header}"', '', POSTLOAD_BODY]
    return '\n'.join(lines) + '\n'


def verify_postload(path, obj):
    """Prove the method and all three absolute/relative targets, including external callees."""
    result = M.compare(str(path), POSTLOAD_SYMBOL, POSTLOAD_RVA, M.FLAGS, obj)
    if result[3] is not None:
        raise ValueError(f'ViewController::PostLoad changed: {result[4]}')
    _, code, _ = M.function_of(obj, POSTLOAD_SYMBOL)
    targets = dict(M.symbol_addresses(POSTLOAD_RVA, code))
    expected = {'?g_36f6118@@3HA': 0x36f6118 - 0x580000,
                '?Load@ViewLoadRegistry_ab1550@@QAEXPBE@Z': 0xab1550,
                '?RegisterView_af37c0@@YAXPAUViewController@@@Z': 0xaf37c0}
    if targets != expected:
        raise ValueError(f'ViewController::PostLoad targets changed: {targets!r}')
    return dict(rva=hex(POSTLOAD_RVA), symbol=POSTLOAD_SYMBOL, bytes=result[1], targets=targets)


def main():
    report_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'client-src/progress-2026-10-08-parallel-audit.json'
    candidates = sorted(set(dependencies(json.loads(report_path.read_text(encoding='utf-8'))) +
                            published_callbacks()))
    existing = existing_instances()
    candidates = [item for item in candidates if item[:2] not in existing]
    header = (GEN / 'BinClasses.h').read_text(encoding='utf-8')
    defined = set(re.findall(r'^struct (?:alignas\([^\n]+?\) )?(\w+)(?: : \w+)?\n\{', header, re.M))
    incomplete = [item for item in candidates if item[1] not in defined and item[0] != 'MetaVirtual2']
    candidates = [item for item in candidates if item not in incomplete]
    print('Unowned reflection callbacks:', len(candidates), flush=True)
    POSTLOAD_PROBE.write_text(render_postload(absolute=True), encoding='utf-8', newline='\n')
    native_obj = M.compile_obj(str(POSTLOAD_PROBE), M.FLAGS)
    verify_postload(POSTLOAD_PROBE, native_obj)
    POSTLOAD_OUT.write_text(render_postload(claims=True), encoding='utf-8', newline='\n')
    # Retire any earlier in-file definition before publishing the separate TU.
    OUT.write_text(render([item for item in candidates if item in published_callbacks()], claims=True),
                   encoding='utf-8', newline='\n')
    M.rebuilt_symbols.__dict__.pop('v', None)
    PROBE.write_text(render(candidates, absolute=True), encoding='utf-8', newline='\n')
    obj = M.compile_obj(str(PROBE), M.FLAGS)
    keep, rejected = [], []
    for item in candidates:
        fn, name, rva, symbol = item
        result = M.compare(str(PROBE), symbol, rva, M.FLAGS, obj)
        if result[3] is None:
            keep.append(item)
        else:
            rejected.append(dict(fn=fn, name=name, rva=hex(rva), bytes=result[1], identical=result[2], first=result[3], detail=result[4]))
    OUT.write_text(render(keep, claims=True), encoding='utf-8', newline='\n')
    M.rebuilt_symbols.__dict__.pop('v', None)
    obj = M.compile_obj(str(OUT), M.FLAGS)
    native_obj = M.compile_obj(str(POSTLOAD_OUT), M.FLAGS)
    postload = verify_postload(POSTLOAD_OUT, native_obj)
    verified = []
    for fn, name, rva, symbol in keep:
        result = M.compare(str(OUT), symbol, rva, M.FLAGS, obj)
        if result[3] is not None:
            raise ValueError(f'Final reflection specialization changed: {symbol}: {result[4]}')
        verified.append(dict(fn=fn, name=name, rva=hex(rva), bytes=result[1], symbol=symbol))
    AUDIT.write_text(json.dumps(dict(verified=verified,rejected=rejected,incomplete=incomplete,postload=postload),indent=2),encoding='utf-8')
    print('Verified callback bodies:',len(verified),'unique RVAs:',len({v['rva'] for v in verified}),
          'rejected:',len(rejected),flush=True)


if __name__ == '__main__':
    main()
